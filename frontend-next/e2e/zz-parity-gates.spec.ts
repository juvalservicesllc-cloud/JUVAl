import { join } from "node:path"
import { DIR, expect, expectSameTab, markTab, row, test, upload, workbookRows } from "./support"

let run = ""
test.beforeAll(async ({ browser }, info) => {
  const page = await browser.newPage({ baseURL: info.project.use.baseURL })
  try { run = await upload(page, "no-demand.xlsx") } finally { await page.close() }
})

for (const width of [360, 1440]) for (const dark of [false, true]) {
  test(`parity gates: ${width}px ${dark ? "dark" : "light"}`, async ({ page }, info) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto("/appearance")
    await page.getByRole("combobox", { name: "Theme" }).selectOption(String(dark))
    await page.goto(`/products?run=${encodeURIComponent(run)}`)
    await expect(page).toHaveURL(new RegExp(`/catalog\\?run=${run}$`))
    await expect(row(page, "E2E pending widget")).toBeVisible()
    await markTab(page)
    for (const name of [/^SKU/, /^ASIN \/ UPC/, /^Record/, /^Issues/]) await expect(page.getByRole("columnheader", { name })).toBeVisible()
    await page.getByRole("combobox", { name: "Provenance field" }).selectOption("roi")
    const filtered = page.waitForResponse((response) => {
      const url = new URL(response.url())
      return url.pathname.endsWith("/records") && url.searchParams.get("provenance_field") === "roi" && url.searchParams.get("provenance_status") === "INFERRED"
    })
    await page.getByRole("combobox", { name: "Provenance status" }).selectOption("INFERRED")
    const result = await (await filtered).json()
    await expect(page.getByRole("button", { name: `Export ${result.pagination.total} results` })).toBeVisible()
    const exportRequest = page.context().waitForEvent("request", (request) => new URL(request.url()).pathname.endsWith("/records/export"))
    await page.getByRole("button", { name: /^Export/ }).click()
    const url = (await exportRequest).url()
    expect(new URL(url).searchParams.get("provenance_field")).toBe("roi")
    expect(new URL(url).searchParams.get("provenance_status")).toBe("INFERRED")
    expect(await workbookRows(page, url, `parity-${width}-${dark}.xlsx`)).toHaveLength(result.pagination.total)
    await page.getByRole("button", { name: "Reset filters" }).click()
    await expect(row(page, "E2E pending widget")).toBeVisible()
    const navigation = page.getByRole("navigation", { name: "Main navigation" })
    await navigation.getByRole("button", { name: "Dashboard", exact: true }).click()
    await page.getByLabel("Run", { exact: true }).selectOption(run)
    await expect(page.getByLabel("Key figures")).toBeVisible()
    await page.getByRole("button", { name: "Donut", exact: true }).click()
    await expect(page.getByLabel("Decision distribution")).toContainText("REVIEW: 2")
    await page.getByRole("button", { name: "Bars", exact: true }).click()
    await page.getByRole("region", { name: "Recent runs" }).locator(`a[href="/runs/${run}"]`).click()
    await page.getByRole("button", { name: "Load batch context and record preview" }).click()
    await expect(page.getByRole("link", { name: "Open batch", exact: true })).toBeVisible()
    const preview = page.getByRole("table", { name: "Run record preview" })
    await expect(preview.getByRole("row")).toHaveCount(4)
    await preview.getByRole("link", { name: "E2E pending widget", exact: true }).click()
    await expect(page.getByRole("button", { name: "Catalog", exact: true })).toHaveAttribute("aria-current", "page")
    const market = page.getByRole("region", { name: "Illustrative market chart" })
    await expect(market).toContainText("DEMO_FIXTURE · NOT VERIFIED")
    await market.getByRole("button", { name: "Bar", exact: true }).click()
    await expect(market.locator("svg rect")).toHaveCount(90)
    await expectSameTab(page)
    await navigation.getByRole("button", { name: "Runs", exact: true }).click()
    await page.getByRole("combobox", { name: "Sort runs", exact: true }).selectOption("records_total")
    await page.getByRole("combobox", { name: "Run sort direction", exact: true }).selectOption("asc")
    if (width > 760) {
      await page.getByRole("button", { name: "Collapse sidebar" }).click()
      await expect(page.locator(".app")).toHaveClass(/sidebar-collapsed/)
      await page.getByRole("button", { name: "Expand sidebar" }).click()
    }
    await navigation.getByRole("button", { name: "Appearance", exact: true }).click()
    await page.getByLabel("Surface hex", { exact: true }).fill("#ffffff")
    await page.getByLabel("Background hex", { exact: true }).fill("#111111")
    await page.getByLabel("Text hex", { exact: true }).fill("#ffffff")
    await page.getByRole("combobox", { name: "Background fit", exact: true }).selectOption("contain")
    await page.getByRole("combobox", { name: "Background position", exact: true }).selectOption("top")
    const preferences = page.locator(".panel").filter({ has: page.getByRole("heading", { name: "Browser preferences", exact: true }) })
    await expect(preferences).toHaveCSS("color", "rgb(0, 0, 0)")
    await expect(preferences).toHaveCSS("background-color", "rgb(255, 255, 255)")
    await expect(page.locator("h1")).toHaveCSS("color", "rgb(255, 255, 255)")
    await page.screenshot({ path: info.outputPath(`parity-appearance-${width}-${dark}.png`), fullPage: true })
    await page.getByRole("button", { name: "Reset appearance defaults" }).click()
    await page.getByRole("combobox", { name: "Theme" }).selectOption(String(dark))
    await navigation.getByRole("button", { name: "Import", exact: true }).click()
    await page.getByRole("switch").focus()
    await page.keyboard.press("Tab")
    await expect(page.getByLabel("Supplier files")).toBeFocused()
    const chooser = page.waitForEvent("filechooser")
    await page.keyboard.press("Enter")
    await (await chooser).setFiles(join(DIR, "files", "no-demand.xlsx"))
    await expect(page.getByLabel("File queue")).toContainText("no-demand.xlsx")
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBe(0)
    await expectSameTab(page)
    await page.screenshot({ path: info.outputPath(`parity-picker-${width}-${dark}.png`), fullPage: true })
  })
}
